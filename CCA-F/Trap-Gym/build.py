"""Builds assets/plain-data.js from the plain-style item files, after validating them.

Source of truth: ../Foundations-Mock-Exam-7/parts/plain/*.json (rules in SPEC-PLAIN.md there).
Also embeds the original Mock 7 version of every item that has a "was" id, for the before/after page.
Usage (from CCA-F/Trap-Gym/): python3 build.py
"""
import json, pathlib, subprocess, sys

here = pathlib.Path(__file__).parent
mock7 = here.parent / "Foundations-Mock-Exam-7"
files = sorted((mock7 / "parts" / "plain").glob("*.json"))
for f in files:
    if subprocess.call([sys.executable, str(mock7 / "validate.py"), "--plain", "--sample", "--stem=35-70", "--avg=16", str(f)],
                       cwd=mock7, stdout=subprocess.DEVNULL):
        sys.exit(f"validation failed for {f.name}; run validate.py on it to see why")

scen, qs = {}, {}
for f in files:
    d = json.loads(f.read_text())
    scen.update({s["id"]: s for s in d["scenarios"]})
    qs.update({q["id"]: q for q in d["questions"]})

# Trap pages may also show questions from the Mock 4-7 plain papers: bundle just the ones they reference.
import re
used = set()
for page in here.glob("*/index.html"):
    for ids in re.findall(r"renderPlain\([^\[]*\[([^\]]*)\]", page.read_text()):
        used.update(re.findall(r'"([^"]+)"', ids))
for f in sorted(here.parent.glob("Foundations-Mock-Exam-*/parts/plain/paper/s*.json")):
    d = json.loads(f.read_text())
    picked = [q for q in d["questions"] if q["id"] in used and q["id"] not in qs]
    if picked:
        scen.update({s["id"]: s for s in d["scenarios"]})
        qs.update({q["id"]: q for q in picked})
missing = used - set(qs)
if missing:
    sys.exit(f"trap pages reference unknown question ids: {sorted(missing)}")

old = {}
for f in sorted((mock7 / "parts").glob("*.json")):
    old.update({q["id"]: q for q in json.loads(f.read_text())["questions"]})
before = {q["was"]: {k: old[q["was"]][k] for k in ("question", "options", "answer", "runnerUp")}
          for q in qs.values() if q.get("was") in old}

data = {"scenarios": list(scen.values()), "questions": list(qs.values())}
(here / "assets" / "plain-data.js").write_text(
    "/* GENERATED by Trap-Gym/build.py from Foundations-Mock-Exam-7/parts/plain/*.json. Edit the JSON, then rebuild. */\n"
    f"window.PLAIN = {json.dumps(data, ensure_ascii=False)};\nwindow.BEFORE = {json.dumps(before, ensure_ascii=False)};\n")
print(f"built {len(qs)} plain items ({len(before)} with a Mock 7 original) from {len(files)} files")
