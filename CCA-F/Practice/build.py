"""Per-domain practice pages + "Traps in this domain" boxes on the domain hubs.

Collects every plain-style question (Mocks 4-7 plain papers, Trap gym practice files), groups them by domain,
writes Practice/data.js and Practice/d1..d5.html, and injects a traps box between
<!-- traps:start --> and <!-- traps:end --> on each domain hub (after the first <div class="wrap">).
Only trap pages that exist are linked. Safe to re-run.
Usage (from CCA-F/): python3 Practice/build.py
"""
import json, pathlib, re

here = pathlib.Path(__file__).resolve().parent
ccaf = here.parent
DOMAINS = {
    "D1": ("D1-Agentic-Architecture", "Agentic Architecture & Orchestration"),
    "D2": ("D2-Tool-Design-MCP", "Tool Design & MCP Integration"),
    "D3": ("D3-Claude-Code", "Claude Code Configuration & Workflows"),
    "D4": ("D4-Prompt-Engineering", "Prompt Engineering & Structured Output"),
    "D5": ("D5-Context-Management", "Context Management & Reliability"),
}
TRAPS = {  # domain -> [(slug, title)]
    "D1": [("prompt-vs-hook", "Prompt or hook?"), ("coordinator-split", "The coordinator's split")],
    "D2": [("tool-picker", "The tool picker"), ("mcp-where-what", "MCP: where and what"), ("tool-failure", "When a tool fails")],
    "D3": [("instruction-home", "Where does this instruction live?"), ("plan-or-do", "Plan or just do it?")],
    "D4": [("extraction-honesty", "Extraction honesty"), ("batch-or-now", "Batch or now?")],
    "D5": [("context-meter", "The context meter"), ("tool-failure", "When a tool fails"), ("who-escalates", "Who escalates?")],
}

sources = []  # (label, file)
for n in (7, 6, 5, 4):
    for f in sorted((ccaf / f"Foundations-Mock-Exam-{n}" / "parts" / "plain" / "paper").glob("s*.json")):
        sources.append((f"Mock {n}", f))
for f in sorted((ccaf / "Foundations-Mock-Exam-7" / "parts" / "plain").glob("trap-*.json")):
    sources.append(("Trap gym", f))

scen, by_dom, ids_by_dom = {}, {d: [] for d in DOMAINS}, {d: [] for d in DOMAINS}
for label, f in sources:
    d = json.loads(f.read_text())
    for s in d["scenarios"]:
        scen[s["id"]] = s
    for q in d["questions"]:
        dom = q["domain"][:2]
        if dom in by_dom and q["id"] not in ids_by_dom[dom]:
            q = dict(q, source=label)
            by_dom[dom].append(q)
            ids_by_dom[dom].append(q["id"])

allq = [q for d in DOMAINS for q in by_dom[d]]
(here / "data.js").write_text("/* GENERATED by Practice/build.py. */\nwindow.PLAIN = "
                              + json.dumps({"scenarios": list(scen.values()), "questions": allq}, ensure_ascii=False)
                              + ";\nwindow.PRACTICE_IDS = " + json.dumps(ids_by_dom) + ";\n")

# A trap page counts as ready when the Trap gym index links it (its list is the one source of truth).
READY = set(re.findall(r'\["([a-z-]+)/", "', (ccaf / "Trap-Gym" / "index.html").read_text()))

def trap_links(dom, prefix):
    return [(f"{prefix}Trap-Gym/{slug}/", t) for slug, t in TRAPS[dom] if slug in READY]

for dom, (folder, name) in DOMAINS.items():
    n = len(by_dom[dom])
    mocks = sorted({q["source"] for q in by_dom[dom]})
    links = " · ".join(f'<a href="{u}">{t}</a>' for u, t in trap_links(dom, "../"))
    page = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{dom} Practice Questions</title>
<meta name="description" content="{n} exam-style practice questions on CCA-F {dom} {name}, each with a plain explanation and a think-it-through walk-through.">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=DM+Sans:wght@400;600&family=Patrick+Hand&display=swap" rel="stylesheet">
<link rel="stylesheet" href="../Trap-Gym/assets/gym.css">
</head>
<body>
<main>
  <div class="crumbs"><a href="../">CCA-F start here</a> · <a href="../{folder}/">{dom} lessons</a> · Practice</div>
  <h1>{dom} practice: {name.replace('&', '&amp;')}</h1>
  <p class="lede">{n} exam-style questions on this domain, from {", ".join(mocks)}. Each tells the whole situation in plain words; all four options work, and one fits best. Answer first, then open “Think it through”.</p>
  {"<div class='box peri'><b>Traps in this domain:</b> " + links + "</div>" if links else ""}
  <div id="qs"></div>
</main>
<script src="data.js"></script>
<script src="../Trap-Gym/assets/plainq.js"></script>
<script>renderPlain(document.getElementById("qs"), window.PLAIN, window.PRACTICE_IDS["{dom}"]);</script>
</body>
</html>
"""
    (here / f"{dom.lower()}.html").write_text(page)

    hub = ccaf / folder / "index.html"
    s = hub.read_text()
    s = re.sub(r"\s*<!-- traps:start -->.*?<!-- traps:end -->", "", s, flags=re.S)
    s = re.sub(r'<div class="wrap">\s*', '<div class="wrap">\n', s, count=1)
    tl = " ".join(f'<a href="{u}">{t}</a>' for u, t in trap_links(dom, "../"))
    box = f"""<!-- traps:start -->
    <div class="intro" id="exam-traps" style="border-left:4px solid #8a6bd1;margin-bottom:18px">
        <h2 style="margin-top:0">Exam traps and practice for this domain</h2>
        <p>On the exam every option in this domain is a sensible practice; these traps decide most questions.
        Each trap page has a simulator and exam-style practice.</p>
        {f'<p class="quicklinks">{tl}</p>' if tl else ''}
        <p><b>Practice:</b> <a href="../Practice/{dom.lower()}.html">{n} plain-style questions on {dom}</a>, each with
        “Explain simply” and “Think it through”. New here? <a href="../">Start here</a>.</p>
    </div>
<!-- traps:end -->

"""
    s = s.replace('<div class="wrap">\n', '<div class="wrap">\n' + box, 1)
    hub.write_text(s)
    print(f"{dom}: {n} questions, {len(trap_links(dom, ''))} trap pages")
