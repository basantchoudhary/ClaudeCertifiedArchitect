"""Builds the plain-style exam page for each converted mock.

For each Foundations-Mock-Exam-<N>/parts/plain/paper/s1..s6.json that is complete (6 files, validator OK):
writes Foundations-Mock-Exam-<N>/plain/questions-plain.js and plain/index.html (from Mock 7's plain page).
Usage (from CCA-F/): python3 build_plain_mocks.py [4 5 6 7]
"""
import json, pathlib, re, subprocess, sys

here = pathlib.Path(__file__).parent
validator = here / "Foundations-Mock-Exam-7" / "validate.py"
template = (here / "Foundations-Mock-Exam-7" / "plain" / "index.html").read_text()
for n in (sys.argv[1:] or ["4", "5", "6", "7"]):
    mock = here / f"Foundations-Mock-Exam-{n}"
    parts = sorted((mock / "parts" / "plain" / "paper").glob("s*.json"))
    if len(parts) != 6:
        print(f"Mock {n}: {len(parts)}/6 scenarios ready, skipped")
        continue
    if subprocess.call([sys.executable, str(validator), "--plain", "--stem=35-70", "--avg=16", *map(str, parts)],
                       cwd=validator.parent, stdout=subprocess.DEVNULL):
        print(f"Mock {n}: validation failed, skipped")
        continue
    scen, qs = [], []
    for p in parts:
        d = json.loads(p.read_text())
        scen += d["scenarios"]
        qs += d["questions"]
    out = mock / "plain"
    out.mkdir(exist_ok=True)
    exam = {"minutes": 120, "passMark": 0.72, "scenarios": scen, "questions": qs}
    (out / "questions-plain.js").write_text(
        f"/* CCA-F Mock {n}, plain style. GENERATED by build_plain_mocks.py from parts/plain/paper/*.json. */\n"
        "window.EXAM = " + json.dumps(exam, ensure_ascii=False, indent=1) + ";\n")
    if n != "7":
        page = template.replace("Mock Exam #7", f"Mock Exam #{n}").replace("Mock 7", f"Mock {n}") \
                       .replace("Mock #7", f"Mock #{n}")
        page = re.sub(r"<p style=\"font-size:\.92em\">The original Mock #\d is still.*?</p>",
                      f'<p style="font-size:.92em">The original Mock #{n} is still <a href="../">here</a>.</p>', page, flags=re.S)
        page = page.replace("This is Mock #%s rewritten after sitting the real exam." % n,
                            "This is Mock #%s rewritten in the style of the real exam." % n)
        (out / "index.html").write_text(page)
    print(f"Mock {n}: built {len(qs)} items")
