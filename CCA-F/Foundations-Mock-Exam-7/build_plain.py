"""Builds the plain-style Mock 7 paper: parts/plain/paper/s*.json -> plain/questions-plain.js, after validating.

Rules: parts/plain/SPEC-PLAIN.md. The page is plain/index.html, which reuses assets/exam.js and exam.css.
Usage (from Foundations-Mock-Exam-7/): python3 build_plain.py
"""
import json, pathlib, subprocess, sys

here = pathlib.Path(__file__).parent
parts = sorted((here / "parts" / "plain" / "paper").glob("s*.json"))
if subprocess.call([sys.executable, str(here / "validate.py"), "--plain", "--stem=35-70", "--avg=16", *map(str, parts)],
                   cwd=here, stdout=subprocess.DEVNULL):
    sys.exit("validation failed; run validate.py --plain --stem=35-70 --avg=16 parts/plain/paper/s*.json")
scen, qs = [], []
for p in parts:
    d = json.loads(p.read_text())
    scen += d["scenarios"]
    qs += d["questions"]
exam = {"minutes": 120, "passMark": 0.72, "scenarios": scen, "questions": qs}
(here / "plain" / "questions-plain.js").write_text(
    "/* CCA-F Mock 7, plain style. GENERATED by build_plain.py from parts/plain/paper/*.json; edit those and rebuild. */\n"
    "window.EXAM = " + json.dumps(exam, ensure_ascii=False, indent=1) + ";\n")
print(f"built {len(qs)} items in {len(scen)} scenarios")
